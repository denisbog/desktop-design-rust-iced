//! Embeds the Lucide icon set (`assets/icons/*.svg`) as a generated table, so
//! `icons.rs` never has to hand-maintain 180 `include_bytes!` arms.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let icons = manifest.join("assets/icons");
    println!("cargo:rerun-if-changed=assets/icons");

    let mut entries: Vec<(String, PathBuf)> = fs::read_dir(&icons)
        .unwrap_or_else(|e| panic!("cannot read {}: {e}", icons.display()))
        .filter_map(Result::ok)
        .map(|e| e.path())
        .filter(|p| p.extension().and_then(|s| s.to_str()) == Some("svg"))
        .map(|p| {
            let name = p.file_stem().and_then(|s| s.to_str()).expect("utf-8 icon name").to_string();
            (name, p)
        })
        .collect();
    entries.sort_by(|a, b| a.0.cmp(&b.0));

    let mut out = String::from(
        "// @generated by build.rs — embedded Lucide SVG icons. Do not edit.\n\
         pub static ICONS: &[(&str, &[u8])] = &[\n",
    );
    for (name, path) in &entries {
        let path = path.to_string_lossy().replace('\\', "/");
        out.push_str(&format!("    ({name:?}, include_bytes!({path:?})),\n"));
    }
    out.push_str("];\n");

    let out_dir = Path::new(&env::var("OUT_DIR").expect("OUT_DIR")).to_path_buf();
    fs::write(out_dir.join("icons.rs"), out).expect("write generated icons");
}
